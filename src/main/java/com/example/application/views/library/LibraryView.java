package com.example.application.views.library;

import com.example.application.data.SampleBook;
import com.example.application.services.SampleBookService;
import com.example.application.views.MainLayout;
import com.vaadin.flow.component.UI;
import com.vaadin.flow.component.grid.Grid;
import com.vaadin.flow.component.grid.GridSortOrder;
import com.vaadin.flow.component.grid.GridVariant;
import com.vaadin.flow.component.html.Paragraph;
import com.vaadin.flow.component.masterdetaillayout.MasterDetailLayout;
import com.vaadin.flow.data.provider.SortDirection;
import com.vaadin.flow.router.BeforeEnterEvent;
import com.vaadin.flow.router.BeforeEnterObserver;
import com.vaadin.flow.router.Menu;
import com.vaadin.flow.router.PageTitle;
import com.vaadin.flow.router.ParentLayout;
import com.vaadin.flow.router.Route;
import com.vaadin.flow.router.RouteParameters;
import io.quarkus.panache.common.Page;
import io.quarkus.panache.common.Sort;
import jakarta.annotation.security.PermitAll;
import org.vaadin.lineawesome.LineAwesomeIconUrl;

/**
 * The list of books. Also the router layout for {@link BookEditView}, which
 * the MasterDetailLayout shows in its detail area next to (or over) the list.
 */
@PageTitle("Library")
@Route(value = "master-detail", layout = MainLayout.class)
@ParentLayout(MainLayout.class)
@Menu(order = 1, icon = LineAwesomeIconUrl.COLUMNS_SOLID)
@PermitAll
public class LibraryView extends MasterDetailLayout implements BeforeEnterObserver {

    private final SampleBookService service;
    private final BookGrid grid;

    public LibraryView(SampleBookService service) {
        this.service = service;
        this.grid = new BookGrid();
        setMaster(grid);
        setDetailPlaceholder(new Paragraph("""
                Select a book to edit it. This is an example view that requires login, \
                originally generated by start.vaadin.com.""") {{
            getStyle().setPadding("var(--vaadin-padding-m)");
        }});
        setMasterSize("30rem", true);
        setDetailSize("25rem");
        addBackdropClickListener(e -> showList());
        addDetailEscapePressListener(e -> showList());
        setSizeFull();
    }

    /**
     * Keeps the grid in sync with the URL, also when the detail view is opened
     * or closed by navigation.
     */
    @Override
    public void beforeEnter(BeforeEnterEvent event) {
        event.getRouteParameters().getLong(BookEditView.BOOK_ID).ifPresentOrElse(
                id -> service.get(id).ifPresent(grid::select),
                () -> {
                    grid.deselectAll();
                    grid.getDataProvider().refreshAll();
                });
    }

    static void showList() {
        UI.getCurrent().navigate(LibraryView.class);
    }

    class BookGrid extends Grid<SampleBook> {
        BookGrid() {
            addComponentColumn(book -> new BookImage(book.getImage()) {{
                setHeight("64px");
            }}).setHeader("Image").setWidth("68px").setFlexGrow(0);
            var nameColumn = addColumn(SampleBook::getName).setHeader("Name").setSortProperty("name")
                    .setAutoWidth(true);
            addColumn(SampleBook::getAuthor).setHeader("Author").setSortProperty("author").setAutoWidth(true);
            addColumn(SampleBook::getPublicationDate).setHeader("Publication date")
                    .setSortProperty("publicationDate").setAutoWidth(true);
            addColumn(SampleBook::getPages).setHeader("Pages").setSortProperty("pages").setAutoWidth(true);
            addColumn(SampleBook::getIsbn).setHeader("ISBN").setSortProperty("isbn").setAutoWidth(true);
            setItems(query -> {
                // Vaadin's sort order and paging to the Panache counterparts
                var sort = Sort.empty();
                for (var order : query.getSortOrders()) {
                    sort = sort.and(order.getSorted(), order.getDirection() == SortDirection.ASCENDING
                            ? Sort.Direction.Ascending : Sort.Direction.Descending);
                }
                return service.list(Page.of(query.getPage(), query.getPageSize()), sort).stream();
            });
            // A stable order, otherwise an edited book may jump elsewhere in the list
            sort(GridSortOrder.asc(nameColumn).build());
            addThemeVariants(GridVariant.NO_BORDER);
            setSizeFull();
            // Selection only navigates, the URL decides what is shown
            asSingleSelect().addValueChangeListener(event -> {
                if (event.isFromClient()) {
                    if (event.getValue() == null) {
                        showList();
                    } else {
                        UI.getCurrent().navigate(BookEditView.class,
                                new RouteParameters(BookEditView.BOOK_ID, event.getValue().getId().toString()));
                    }
                }
            });
        }
    }
}
